let currentLanguage = "en";

export function getLanguage() {
  return currentLanguage;
}

export function t(key, vars = {}) {
  const dict = translations[currentLanguage] || translations.en;
  const fallback = translations.en;
  let value = dict[key] ?? fallback[key] ?? key;
  for (const [name, content] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(content));
  }
  return value;
}

export function formatNumberForLanguage(value) {
  return new Intl.NumberFormat(currentLanguage === "es" ? "es-EC" : "en-US").format(Math.round(value * 100) / 100);
}

export function formatIsoForLanguage(value) {
  return new Intl.DateTimeFormat(currentLanguage === "es" ? "es-EC" : "en-US", {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit"
  }).format(new Date(value));
}

export function formatPredictionTimestampForLanguage(value) {
  if (!value) return t("pending");
  return new Intl.DateTimeFormat(currentLanguage === "es" ? "es-EC" : "en-US", {
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit"
  }).format(new Date(value));
}

export function relativeTimestampForLanguage(value) {
  const diffMinutes = Math.max(1, Math.round((Date.now() - new Date(value).getTime()) / 60000));
  if (currentLanguage === "es") {
    if (diffMinutes < 60) return `hace ${diffMinutes} min`;
    const diffHours = Math.round(diffMinutes / 60);
    if (diffHours < 24) return `hace ${diffHours} h`;
    return `hace ${Math.round(diffHours / 24)} d`;
  }

  if (diffMinutes < 60) return `${diffMinutes}m ago`;
  const diffHours = Math.round(diffMinutes / 60);
  if (diffHours < 24) return `${diffHours}h ago`;
  return `${Math.round(diffHours / 24)}d ago`;
}

export function translateTimeLeft(value) {
  if (currentLanguage === "en") return value;
  if (value === "Settled") return "Finalizado";
  if (value === "Winner declared") return "Ganador declarado";
  if (value === "Refund available") return "Reembolso disponible";
  if (value === "Awaiting verdict") return "Esperando veredicto";
  if (value.includes(" left")) return value.replace(" left", " restantes");
  return value;
}

export function applyStaticTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  root.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = t(element.dataset.i18nHtml);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });

  document.documentElement.lang = t("htmlLang");

  const toggle = root.querySelector("[data-lang-toggle]") || document.querySelector("[data-lang-toggle]");
  if (toggle) {
    toggle.textContent = t("toggleLabel");
    toggle.setAttribute("aria-label", currentLanguage === "en" ? "Switch to Spanish" : "Cambiar a inglés");
  }
}

export function setLanguage(language) {
  currentLanguage = language === "es" ? "es" : "en";
  applyStaticTranslations();
  window.dispatchEvent(new CustomEvent("languagechange", { detail: { language: currentLanguage } }));
}

export function toggleLanguage() {
  setLanguage(currentLanguage === "en" ? "es" : "en");
}

export function initLanguage() {
  applyStaticTranslations();

  const toggle = document.querySelector("[data-lang-toggle]");
  if (toggle && !toggle.dataset.bound) {
    toggle.dataset.bound = "true";
    toggle.addEventListener("click", toggleLanguage);
  }
}
